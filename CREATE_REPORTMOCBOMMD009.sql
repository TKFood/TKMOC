/*
  frmREPORTMOCBOM「依製令(製程排序)」分頁用的新資料表
  [TKMOC].[dbo].[REPORTMOCBOMMD009]
  = 與 [TKMOC].[dbo].[REPORTMOCBOM] 相同欄位 + [MD009] 製程代號（來自 [TK].dbo.BOMMD.MD009）
  不會修改原本的 [REPORTMOCBOM]
*/
USE [TKMOC]
GO

IF OBJECT_ID(N'[dbo].[REPORTMOCBOMMD009]', N'U') IS NULL
BEGIN
    --複製 REPORTMOCBOM 的欄位結構（含 ID 的 IDENTITY），不複製資料
    SELECT *
    INTO [dbo].[REPORTMOCBOMMD009]
    FROM [dbo].[REPORTMOCBOM]
    WHERE 1 = 0;

    --新增製程代號
    ALTER TABLE [dbo].[REPORTMOCBOMMD009] ADD [MD009] NVARCHAR(10) NULL;
END
GO

--ID 主鍵（REPORTMOCBOM 的 ID 若不是 IDENTITY，請略過這段）
IF NOT EXISTS (SELECT 1 FROM sys.key_constraints WHERE [type] = 'PK' AND [parent_object_id] = OBJECT_ID(N'[dbo].[REPORTMOCBOMMD009]'))
   AND COLUMNPROPERTY(OBJECT_ID(N'[dbo].[REPORTMOCBOMMD009]'), 'ID', 'IsIdentity') = 1
BEGIN
    ALTER TABLE [dbo].[REPORTMOCBOMMD009] ADD CONSTRAINT [PK_REPORTMOCBOMMD009] PRIMARY KEY CLUSTERED ([ID]);
END
GO

--確認結構
SELECT COLUMN_NAME, DATA_TYPE, CHARACTER_MAXIMUM_LENGTH, NUMERIC_PRECISION, NUMERIC_SCALE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'REPORTMOCBOMMD009'
ORDER BY ORDINAL_POSITION;
GO
