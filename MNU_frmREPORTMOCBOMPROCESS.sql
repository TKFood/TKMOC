-- 將新表單 frmREPORTMOCBOMPROCESS 加入選單（放在與 frmREPORTMOCBOM 相同的主選單下）
-- 請先確認 MNU_SUBMENU / MNU_SUBMENULogin 的實際欄位，若有其他必填欄位請一併補上
-- 在 dbconn 指向的資料庫執行

INSERT INTO MNU_SUBMENU (FRM_CODE, FRM_NAME, MENUPARVAL)
SELECT 'frmREPORTMOCBOMPROCESS', N'製令BOM報表-生產說明維護', MENUPARVAL
FROM MNU_SUBMENU
WHERE FRM_CODE = 'frmREPORTMOCBOM'
AND NOT EXISTS (SELECT 1 FROM MNU_SUBMENU WHERE FRM_CODE = 'frmREPORTMOCBOMPROCESS');

-- 開放權限：比照目前可使用 frmREPORTMOCBOM 的使用者
INSERT INTO MNU_SUBMENULogin (FRM_CODE, UserName)
SELECT 'frmREPORTMOCBOMPROCESS', UserName
FROM MNU_SUBMENULogin
WHERE FRM_CODE = 'frmREPORTMOCBOM'
AND UserName NOT IN (SELECT UserName FROM MNU_SUBMENULogin WHERE FRM_CODE = 'frmREPORTMOCBOMPROCESS');
